import * as assert from 'node:assert';
import { execFile, spawn } from 'node:child_process';
import * as fs from 'node:fs/promises';
import * as os from 'node:os';
import * as path from 'node:path';

import { runMcpInstall } from './mcpInstall';

suite('CLI main', () => {
  let tempDirectory: string;
  let cwd: string;
  let homeDirectory: string;
  let outCliPath: string;
  let outMcpEntryPath: string;

  setup(async () => {
    tempDirectory = await fs.mkdtemp(path.join(os.tmpdir(), 'coggit-cli-main-'));
    cwd = path.join(tempDirectory, 'cwd');
    homeDirectory = path.join(tempDirectory, 'home');
    await fs.mkdir(cwd, { recursive: true });
    outCliPath = path.resolve(__dirname, 'main.js');
    outMcpEntryPath = path.resolve(__dirname, 'mcp-stdio.js');
    await fs.writeFile(outMcpEntryPath, "process.stdout.write('runtime');\n");
  });

  teardown(async () => {
    await fs.rm(outMcpEntryPath, { force: true });
    await fs.rm(tempDirectory, { recursive: true, force: true });
  });

  test('runs mcp install from outside a CogGit project', async () => {
    const first = await runCli(['mcp', 'install', '--json'], cwd, homeDirectory);
    const parsed = JSON.parse(first.stdout) as Record<string, unknown>;

    assert.strictEqual(first.stderr, '');
    assert.strictEqual(parsed.activeVersion, '0.0.0-development');
    assert.match(String(parsed.activeIntegrity), /^sha256:[a-f0-9]{64}$/);
    assert.strictEqual(parsed.changed, true);

    const second = await runCli(['mcp', 'install'], cwd, homeDirectory);
    assert.strictEqual(second.stderr, '');
    assert.match(second.stdout, /CogGit MCP launcher:/);
    assert.match(second.stdout, /Changed: no/);
  });

  test('entry accepts a positional kind synonym and rejects conflicts', async () => {
    const positional = await runCli(['entry', 'standard'], cwd, homeDirectory);
    const option = await runCli(['entry', '--kind', 'standard'], cwd, homeDirectory);
    const defaultForm = await runCli(['entry'], cwd, homeDirectory);
    assert.strictEqual(positional.stderr, '');
    assert.strictEqual(positional.stdout, option.stdout);
    assert.notStrictEqual(positional.stdout, defaultForm.stdout);

    const block = await runCli(['entry', 'standard', '--format', 'block'], cwd, homeDirectory);
    assert.match(block.stdout, /<!-- coggit:begin system-prompt kind=standard /);
    assert.match(block.stdout, /generated by `coggit entry`/);

    const agreeing = await runCli(['entry', 'minimal', '--kind', 'minimal'], cwd, homeDirectory);
    assert.strictEqual(agreeing.stdout, defaultForm.stdout);

    const conflict = await runCliCapture(['entry', 'standard', '--kind', 'minimal'], cwd, homeDirectory);
    assert.strictEqual(conflict.code, 1);
    assert.match(conflict.stderr, /conflicting kinds/);

    const invalid = await runCliCapture(['entry', 'bogus'], cwd, homeDirectory);
    assert.strictEqual(invalid.code, 1);
    assert.match(invalid.stderr, /must be one of: minimal, standard/);
  });

  test('skills guards help before touching the payload and fails loud without one', async () => {
    // The help guard answers from any cwd without looking for the payload.
    const help = await runCli(['skills', '--help'], cwd, homeDirectory);
    assert.strictEqual(help.stderr, '');
    assert.match(help.stdout, /Usage: coggit skills \[options\]/);
    assert.match(help.stdout, /--json/);
    assert.match(help.stdout, /never writes an agent directory/);

    // The compiled test tree carries no skills/ payload, so the announce must
    // refuse loudly (user-facing, exit 1) rather than print a dangling path.
    const missing = await runCliCapture(['skills'], cwd, homeDirectory);
    assert.strictEqual(missing.code, 1);
    assert.strictEqual(missing.stdout, '');
    assert.match(missing.stderr, /skill payload missing: .*SKILL\.md/);
  });

  test('snapshot --json keeps stdout machine-parseable (no debug pollution)', async () => {
    // Regression: a stray debug console.log inside the acceptance flow once
    // prefixed stdout and broke JSON.parse for every machine consumer,
    // including the MCP stdio surface that shares the code path.
    const workspace = path.join(cwd, 'project');
    await fs.mkdir(path.join(workspace, 'src'), { recursive: true });
    await fs.mkdir(path.join(workspace, 'cog'), { recursive: true });
    await fs.mkdir(path.join(workspace, '.coggit'), { recursive: true });
    await fs.writeFile(path.join(workspace, '.coggit', 'config.yaml'), 'source_root: src\ncognition_root: cog\n');
    await fs.writeFile(path.join(workspace, 'src', 'tracked.ts'), 'export const tracked = 1;\n');

    const result = await runCli(['snapshot', '--json'], workspace, homeDirectory);
    assert.strictEqual(result.stderr, '');
    const parsed: unknown = JSON.parse(result.stdout);
    assert.ok(typeof parsed === 'object' && parsed !== null);
  });

  test('the INSTALLED launcher completes the MCP stdio handshake', async function () {
    // Regression: the self-contained payload bundled pathscope's ESM fdir
    // entry, whose createRequire(import.meta.url) is undefined inside a CJS
    // bundle — mcp install reported success while every installed launcher
    // exited 1 before the handshake. A stub payload passes the other tests,
    // so this one drives the REAL esbuild artifact through the real install
    // layout and speaks MCP to the installed launcher like a host would.
    this.timeout(30000);
    const bundledPayload = path.resolve(
      __dirname,
      '../../../..',
      'packages',
      'cli',
      'dist',
      'mcp-stdio.js',
    );
    await fs.access(bundledPayload); // pnpm test builds first; fail loud if run bare.

    const scratch = await fs.mkdtemp(path.join(os.tmpdir(), 'coggit-mcp-handshake-'));
    try {
      const installation = JSON.parse(
        await runMcpInstall({
          bundledEntryPath: bundledPayload,
          version: '0.0.0-development',
          installedBy: 'cli-main-test',
          homeDirectory: scratch,
          json: true,
        }),
      ) as { launcherPath: string };
      assert.match(installation.launcherPath, /coggit-mcp\.js$/);

      const lines = await speakMcp(installation.launcherPath, scratch, [
        {
          jsonrpc: '2.0',
          id: 1,
          method: 'initialize',
          params: {
            protocolVersion: '2024-11-05',
            capabilities: {},
            clientInfo: { name: 'coggit-handshake-test', version: '0.0.0' },
          },
        },
        { jsonrpc: '2.0', method: 'notifications/initialized' },
        { jsonrpc: '2.0', id: 2, method: 'tools/list' },
      ]);

      const init = lines.find((line) => line.id === 1 && line.result) as
        | { result: { protocolVersion: string; serverInfo: { name: string } } }
        | undefined;
      assert.ok(init, 'no initialize response');
      assert.strictEqual(init.result.serverInfo.name, 'coggit');

      const tools = lines.find((line) => line.id === 2 && line.result) as
        | { result: { tools: unknown[] } }
        | undefined;
      assert.ok(tools, 'no tools/list response');
      assert.ok(Array.isArray(tools.result.tools));
    } finally {
      await fs.rm(scratch, { recursive: true, force: true });
    }
  });

  /**
   * Speaks newline-delimited JSON-RPC to the installed launcher like an MCP
   * host: write the messages, close stdin (the stdio transport then winds
   * down), and return every parsed response line. A hard timer kills a
   * launcher that never answers, so the failure carries both streams.
   */
  async function speakMcp(
    launcherPath: string,
    workingDirectory: string,
    messages: readonly unknown[],
  ): Promise<Array<{ id?: number; result?: unknown; error?: unknown }>> {
    return new Promise((resolve, reject) => {
      const child = spawn(process.execPath, [launcherPath], {
        cwd: workingDirectory,
        stdio: ['pipe', 'pipe', 'pipe'],
      });
      const stdout: Buffer[] = [];
      const stderr: Buffer[] = [];
      const timer = setTimeout(() => {
        child.kill();
        reject(new Error(
          `launcher handshake timed out\nstdout: ${Buffer.concat(stdout).toString('utf8')}\n`
            + `stderr: ${Buffer.concat(stderr).toString('utf8')}`,
        ));
      }, 20000);
      child.stdout.on('data', (chunk: Buffer) => stdout.push(chunk));
      child.on('error', (error) => {
        clearTimeout(timer);
        reject(error);
      });
      child.on('close', (code) => {
        clearTimeout(timer);
        const lines = Buffer.concat(stdout).toString('utf8').split('\n')
          .map((line) => line.trim())
          .filter((line) => line !== '');
        if (lines.length === 0) {
          reject(new Error(
            `launcher exited (code ${code}) without an MCP response\n`
              + `stderr: ${Buffer.concat(stderr).toString('utf8')}`,
          ));
          return;
        }
        const parsed: Array<{ id?: number; result?: unknown; error?: unknown }> = [];
        try {
          for (const line of lines) {
            parsed.push(JSON.parse(line) as { id?: number; result?: unknown; error?: unknown });
          }
        } catch {
          reject(new Error(
            `launcher stdout broke newline-delimited JSON: ${lines.find((l) => !l.startsWith('{'))}\n`
              + `stderr: ${Buffer.concat(stderr).toString('utf8')}`,
          ));
          return;
        }
        resolve(parsed);
      });

      for (const message of messages) {
        child.stdin.write(`${JSON.stringify(message)}\n`);
      }
      child.stdin.end();
    });
  }

  async function runCli(
    args: readonly string[],
    workingDirectory: string,
    userProfile: string,
  ): Promise<{ stdout: string; stderr: string }> {
    return new Promise((resolve, reject) => {
      execFile(
        process.execPath,
        [outCliPath, ...args],
        {
          cwd: workingDirectory,
          env: {
            ...process.env,
            HOME: userProfile,
            USERPROFILE: userProfile,
          },
        },
        (error, stdout, stderr) => {
          if (error) {
            reject(new Error(`${error.message}\n${stderr}`));
            return;
          }
          resolve({ stdout, stderr });
        },
      );
    });
  }

  async function runCliCapture(
    args: readonly string[],
    workingDirectory: string,
    userProfile: string,
  ): Promise<{ code: number; stdout: string; stderr: string }> {
    return new Promise((resolve, reject) => {
      execFile(
        process.execPath,
        [outCliPath, ...args],
        {
          cwd: workingDirectory,
          env: {
            ...process.env,
            HOME: userProfile,
            USERPROFILE: userProfile,
          },
        },
        (error, stdout, stderr) => {
          if (error && typeof error.code === 'number') {
            resolve({ code: error.code, stdout, stderr });
            return;
          }
          if (error) {
            reject(new Error(`${error.message}\n${stderr}`));
            return;
          }
          resolve({ code: 0, stdout, stderr });
        },
      );
    });
  }
});
